/** Flat location options: Country, then "City, Country" for major cities. */
export const HUNT_LOCATION_OPTIONS: string[] = (() => {
  const out: string[] = [];
  const countries = Object.keys(HUNT_COUNTRY_CITIES).sort((a, b) => a.localeCompare(b));
  // Also include countries from a wider UN-style list that may lack city maps yet
  const extraCountries = [
    'Andorra', 'Antigua and Barbuda', 'Bahamas', 'Barbados', 'Belize', 'Bhutan', 'Brunei',
    'Burundi', 'Cape Verde', 'Central African Republic', 'Chad', 'Comoros', 'Congo',
    'Democratic Republic of the Congo', 'Djibouti', 'Dominica', 'Equatorial Guinea',
    'Eritrea', 'Eswatini', 'Gabon', 'Gambia', 'Grenada', 'Guinea', 'Guinea-Bissau',
    'Haiti', 'Kiribati', 'Kosovo', 'Lesotho', 'Liberia', 'Liechtenstein', 'Malawi',
    'Maldives', 'Mali', 'Marshall Islands', 'Mauritania', 'Micronesia', 'Monaco',
    'Niger', 'Palau', 'Palestine', 'Saint Kitts and Nevis', 'Saint Lucia',
    'Saint Vincent and the Grenadines', 'Samoa', 'San Marino', 'Sao Tome and Principe',
    'Seychelles', 'Sierra Leone', 'Solomon Islands', 'Somalia', 'South Sudan',
    'Syria', 'Tajikistan', 'Timor-Leste', 'Togo', 'Tonga', 'Turkmenistan', 'Tuvalu',
    'Vanuatu', 'Vatican City',
  ];
  for (const c of countries) {
    out.push(c);
    for (const city of HUNT_COUNTRY_CITIES[c] || []) {
      // Skip if city already equals country name (Singapore)
      if (city.toLowerCase() === c.toLowerCase()) continue;
      out.push(`${city}, ${c}`);
    }
  }
  for (const c of extraCountries) {
    if (!out.includes(c)) out.push(c);
  }
  return out;
})();

export function filterOptions(options: string[], query: string, limit = 80): string[] {
  const q = (query || '').trim().toLowerCase();
  if (!q) return options.slice(0, limit);
  const starts: string[] = [];
  const includes: string[] = [];
  for (const opt of options) {
    const low = opt.toLowerCase();
    if (low.startsWith(q)) starts.push(opt);
    else if (low.includes(q)) includes.push(opt);
    if (starts.length + includes.length >= limit) break;
  }
  return [...starts, ...includes].slice(0, limit);
}
